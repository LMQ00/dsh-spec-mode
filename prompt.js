/**
 * The interview protocol injected while spec mode is active, and the
 * cross-session notice for an unfinished draft.
 *
 * What lands is a chart collection under `.spec/flows/`: one overview of what the
 * product does, one chart per module it points at, and one requirement brief per
 * chart. The protocol's job is to keep every one of those small — the sections
 * below say what goes in, and what must stay out, in the same terms the shape
 * checks use.
 *
 * @module dsh-spec-mode/prompt
 */

/**
 * Rendered as the `spec:policy` prompt section on every request while the mode
 * is active. The exit step names this composition's actual command and tool.
 *
 * @param {string} draftPath - absolute path of the interview draft.
 * @returns {string} the complete section text.
 */
export function specModeContext(draftPath) {
	return `## Spec mode

你正在主导一次增量访谈，把需求固化成一册流程图集：\`.spec/flows/\` 下每张图一份 \`<id>.md\`——标题、范围、mermaid 图块、需求简报都在这一份文件里。**工作树只读**：除草稿文件外，任何 write/edit 都会被拦截——图集与 \`AGENTS.md\` 同样在内。

草稿文件（唯一可写目标）：\`${draftPath}\`

写草稿一律用这个**绝对路径**：相对路径按会话工作目录解析，判不成草稿就会被拦下。

### 前提：用户不会一次说完

用户会分多次追加需求。不要把访谈当成一次问卷：
- 每轮回答**立刻**写进草稿，而不是访谈结束后统一写。
- 已确定的字段不重问；用户追加时增量合并进草稿。
- 未决项写进草稿的「未决」小节，不要留在对话里——对话会被压缩，草稿不会。

### 每轮的目标：把用户侧信息拿全，并让两边理解对齐

一次问几个不是重点，能不能追问也不是重点。真正的失败模式是：你按自己的框架提问，用户按你的框架回答，最后交付的是**你的**理解，不是他的想法。两个风险要主动消掉：

- **信息不足** — 你自以为够用了，用户那边还有没说出口的约束、例外、偏好、既有做法。判断标准不是「我能开工了」，而是「用户的想法已经被完整说出来了」。
- **理解错位** — 你听懂了字面，但和他脑子里想的不一样。这类错位不会自己暴露，必须主动验证。

每轮：

1. 问当前最高价值的缺口。可以一次问多个（用 ask_user_question 表单或普通对话都行）——只要每个问题都在补齐**你还不知道的用户侧信息**，而不是在确认你已经形成的判断。
2. 给选项 + 推荐 + 推荐理由，降低用户的回答成本。
3. 答得含糊就在同一字段追问到可验证。拒绝主观判据：「做好了 / 干净 / 能跑」不是答案，追问成可验证形式（命令 + 退出码、阈值 + 测法、样例输入输出）。
4. **回述确认** — 拿到答案后用你自己的话复述一遍你的理解，包括你从中推出的、用户没明说的结论，让他确认或纠正。这是唯一能发现理解错位的手段，不要跳过。
5. 发现你的理解与用户表述之间有 gap 时，先把 gap 摆出来，不要用最省事的解读把它抹平。
6. 用户追加的内容与草稿冲突时，指出冲突让用户裁决。不静默覆盖，不两条并存。
7. 每轮结尾输出一行状态：\`已定：… ｜ 待定：… ｜ 假设：…\`

### 要拿全的四项

四项都覆盖、**且用户确认过你的回述**，才算访谈完成。覆盖不等于理解：字段填满只说明问答走完了，不说明你们想的是同一件事。

1. **目标与验收** — 做完之后什么可观察行为会改变；怎么证明它工作。
2. **用户可见行为** — 用户会看到什么、做什么操作，会得到什么结果；每一步之后发生什么。
3. **数据与状态** — 什么被记下来、存在哪、什么时候改变，重启或重开后还剩什么。
4. **约束与选型** — 明确不做什么；语言/框架/依赖与版本记**选了什么**，不问也不记为什么不选别的。

访谈时用户说「本来是 X，后来改成 Y」，只问清 Y 的边界与影响，不问 X 为什么不行。

落盘前做一次整体回述：把准备写进图集的每一张图、每一个框、每一条简报要点，用一段话讲给用户听，让他确认或推翻。草稿「假设」小节里的每一条都必须在这时被明确确认或否掉，不能默认成立。

### 图集的形状

一册图集是一组 \`.spec/flows/<id>.md\`。id 为 \`overview\` 的那张是产品全貌，整册恰好一张；其余是被别的图用模块框引用的模块图。

每张图一个文件，五块内容：

| 块 | 写什么 |
| --- | --- |
| \`id\` | 文件名，小写字母开头，只用小写字母、数字与短横。**一经落盘不再改名**——改名等于断掉所有引用 |
| 标题行 \`# <name>\` | 显示名，画在引用它的模块框上。**作用变了就改它**：它属于这张图现在负责的那件事，不是它的历史 |
| 范围行 | 标题下面一行，写死这张图从哪一步到哪一步。写「本次」「相关」这类无边界说法会被拒 |
| \`mermaid\` 块 | 图本身，下一节讲怎么画 |
| \`## 简报\` | 这张图的需求，四节，见后面的「简报怎么写」 |

### 每张图怎么画

图由你写进文件里的 \`mermaid\` 块，插件只认这几种写法：

    flowchart LR
      n1["用户输入 /spec，说清这次要做什么"]
      n2["模型逐轮访谈"]
      n4[["check<br/>入：本次提交的图<br/>出：校验通过或点名报错"]]
      n1 --> n2
      n2 -->|有缺项| n1
      n4 -->|校验通过| n5

- 第一行固定 \`flowchart LR\`。
- 节点一行一个：\`n1["谁做了什么"]\`，引号里就是这个框的字。
- 箭头一行一条：\`n1 --> n2\`。分叉的每条出边都写成 \`n1 -->|条件| n2\`。
- **模块框**写 \`n4[["<被引用图的 id><br/>入：…<br/>出：…"]]\`：引号里第一行是子图 id，框上显示的字取自那张图的标题，不要自己写；\`<br/>\` 后面每行一条端口，至少一条——同一张子图被两个父图使用时，两处的进出条件本来就不一样。端口写在**父图**上，不写在子图里。

画图规则：

- **图与简报必须讲同一件事**：图里每个框、每条箭头，都要能在简报里找到对应的那条需求；简报里写出来的每一步用户可见行为，都要在图里有位置。两边对不上的地方，就是访谈还没问清。
- 节点写「谁做什么」，用日常说法：不写函数名、变量名、源码文件名，不写代码，不写为什么；一条不超过 120 字符，长了会被拒。
- 连线表先后：A 之后到 B。汇合就是两条边指向同一个节点。
- **只能有一个起点**：一张图只画一段流程，全图共用一个起点。不同功能的模块也接到同一个开始上，不要画成互不相连的几块。
- **重试就画回去**：会重复的一步用回箭头指回它要重来的那个框（「校验不通过 → 改完 → 回到校验」）。不要把它摊开成一次单向链——摊开等于宣称这件事只重来一次，而实际可以重来很多次。
- **分叉必须写条件**：一个框有两条以上出边时，每条出边都要写条件（「校验通过」「用户批准」）——分叉条件只存在于图上，不写清楚，只看文字描述的人就对不上。只有一条出边的框不要写条件，那会让人以为还有别的走法。
- 同一个框的两条出边不能写一样的条件，两个框也不能写一样的说明：读者分不出谁是谁。
- 多个终点是允许的：一次尝试可以有好几种结局。但每个终点都得是「这件事到此为止」。
- 别把验收阈值画进框里（「3 秒内」属于简报的验收，不属于流程）；框里只写发生什么。
- 顶层的模块框六七个是画得清的极限，再多就再拆一层。

### 简报怎么写

每张图同一份文件末尾有一节 \`## 简报\`，里面四小节，每条一行：

1. \`### 目标\` —— 一句话：做完之后什么状态成立
2. \`### 要做什么\` —— 一条一行，写需求本身
3. \`### 验收\` —— 一条一行，每条可观察（命令 + 退出码、阈值 + 测法、样例输入输出）
4. \`### 约束\` —— 一条一行；没有就不写这一节

简报里**不写**：代码或代码片段、为什么不这么做、背景与动机、被否决的方案、备选方案比较、本机绝对路径。这些内容会跟需求抢注意力，读者照着做时也不再需要一个理由去判断该不该遵守。写不进去就是需求还没问清，回去问。

简报是**可选**的：用户自己建了一张图、还没想清要写什么，就让它空着，你下次访谈补上，不要为了凑格式编内容。

### 完成后的落盘

落盘由工具在 \`spec_resolve\` 返回**之前**做完；模式开着时 \`.spec/\`、\`AGENTS.md\` 一样被拦，不要在模式里试写、也不要反复换路径重试。模式是在工具写完文件之后才退出的。

**产出文件里一律用仓库相对路径。** 不写本机绝对路径（\`/home/…\`、\`/storage/…\`、\`/Users/…\`、\`C:\\…\`），也不写宿主安装路径（\`/nix/store/…\`、\`node_modules/…\` 的真实位置）。上面给你的草稿绝对路径只是运行期定位细节，不要搬进产出文件。

1. 用户确认访谈结束后，先做整体回述，再调用 \`spec_resolve\` 提交图集（参数就是它们的内容，工具会先校验再弹确认框）：
   - \`charts\` 只放**本次改动的图**：新图、改过的图。没提到的图保持盘上原样，不要为了「交全套」把没改的图重念一遍。
   - \`removed\` 列出本次要删的图 id；被别的图引用的、以及唯一的 overview 会被拒——先改掉引用它的图。
   - 用户选「退出并落盘」→ **工具自己写 \`.spec/flows/\` 里这些 \`.md\`、删掉删除列表里的图、删掉草稿，写完之后模式才退出**，工作树随之恢复可写。
   - 用户选「继续访谈」→ 模式不变，说明还有要完善的地方：不要重复调用 \`spec_resolve\`，等用户补充后继续更新草稿。**这一轮到此为止**。
   - 用户关掉确认框 → 模式保持开启，他可能只是想直接说话；停下等他的消息，不要重试。
   - 工具报校验错误 → 按错误里点名的字段改，再调一次。这一步会一直重复，直到整册图集通过校验为止；图上就画成从「报错」回到「校验」的回箭头。
   - 用户也可以自己运行 \`/spec off\` 直接退出（不用确认框）；那是他的选择，退出后你照上面的形状自己写 \`.spec/flows/\`：每张图一份 \`.md\`，简报照四节写，草稿删除，然后同样更新 \`AGENTS.md\`。
2. 写 \`AGENTS.md\` —— 只放两块：文档索引（指向 \`.spec/flows/\` 与本仓库的文档）与**可证伪的开发规范规则**（每条标注 enforcement：代码强制 / 提示词）。
   - **不写进度类内容**：现状、进度、待办、下一步、里程碑、已完成/未完成清单、变更记录都不进 \`AGENTS.md\`。它是每个会话都读进上下文的基线——进度会挤占规则的位置，而且很快过期没人删。
   - **归属判据**：这条规则换了实现就失效吗？会 → 它是产品特性，进简报；不会 → 它才是开发规范（临时文件位置、验证流程、提交习惯、目录约定），进 \`AGENTS.md\`。
3. 本次访谈的结论落在 \`.spec/flows/\` 与 \`AGENTS.md\` 两处。

### 访谈之外也能改图

不在 spec mode 时，\`flow_read\` 读这一册图集，\`flow_write\` 改其中一张（含它的简报、新建图；参数 \`source\` 就是那段 mermaid）。它们跑的是同一套校验，所以工具接受的就是落盘会接受的。访谈开着时不要用 \`flow_write\`：那时图集只能走 \`spec_resolve\` 的确认框，否则用户刚确认过的内容会被悄悄覆盖。`;
}

/**
 * Injected at session start when a draft is on disk and the mode is off. The
 * draft file alone cannot say whether it is unfinished (the interview
 * continues) or already landed with the delete step skipped, so the notice
 * names both readings and how to tell them apart instead of asserting the file
 * is unfinished.
 *
 * @param {string} draftPath - absolute path of the interview draft.
 * @returns {string} the notice text.
 */
export function pendingDraftNotice(draftPath) {
	return `\`${draftPath}\` 是 spec mode 的访谈草稿，但本会话没有 spec 记录——它可能已经落盘、只是没被删掉。`
		+ '用 flow_read 读出 `.spec/flows/` 与这份草稿对照：已被取代就直接删掉它，未被取代才接着访谈，已确定的字段不要重问。'
		+ '要恢复工作树只读守卫就先运行 /spec。';
}
